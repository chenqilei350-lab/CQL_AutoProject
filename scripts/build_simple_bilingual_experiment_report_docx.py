#!/usr/bin/env python3
"""Build a concise bilingual experiment report from verified project results."""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

from build_complete_experiment_report_docx import (
    BLUE,
    INK,
    MUTED,
    ROOT,
    add_body,
    add_bullets,
    add_callout,
    add_figure,
    add_source_note,
    add_table,
    configure_document,
    create_charts,
    draw_grouped_bar_chart,
    set_paragraph_border_bottom,
    set_run_font,
)


BUILD_DIR = ROOT / "tmp" / "bilingual_experiment_report_20260804"
OUTPUT = ROOT / "docs" / "reports" / "AUT_KG_Simple_Bilingual_Experiment_Report_2026-08-04.docx"


def add_bilingual(doc: Document, zh: str, en: str) -> None:
    """Add one Chinese paragraph followed by a visually secondary English paragraph."""

    add_body(doc, zh, after=3)
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(8)
    run = paragraph.add_run(en)
    set_run_font(run, size=9.5, color=MUTED, italic=True)


def add_bilingual_bullets(doc: Document, pairs: list[tuple[str, str]]) -> None:
    items = [f"{zh} / {en}" for zh, en in pairs]
    add_bullets(doc, items)


def set_report_header(doc: Document) -> None:
    for section in doc.sections:
        paragraph = section.header.paragraphs[0]
        paragraph.text = "AUT KG Extraction Pipeline  |  Bilingual Experiment Report"
        paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
        set_run_font(paragraph.runs[0], size=8.5, color=MUTED, bold=True)


def build_document() -> Path:
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    industrial_chart, relation_chart, easg_chart = create_charts()
    ablation_chart = BUILD_DIR / "relation_candidate_ablation_edge_f1.png"
    draw_grouped_bar_chart(
        ablation_chart,
        "Relation candidate ablation: Edge F1",
        ["Minimal", "Deterministic", "LLM Judge"],
        [("Edge F1", [0.0476, 0.0476, 0.0564], "#C00020")],
        y_max=0.10,
    )

    doc = Document()
    configure_document(doc)
    set_report_header(doc)

    kicker = doc.add_paragraph()
    kicker.paragraph_format.space_before = Pt(18)
    kicker.paragraph_format.space_after = Pt(8)
    run = kicker.add_run("TU BERLIN · INDUSTRIAL AUTOMATION PROJECT")
    set_run_font(run, size=10, bold=True, color=BLUE)

    title = doc.add_paragraph(style="Title")
    title.paragraph_format.space_after = Pt(4)
    title_run = title.add_run("AUT KG Extraction Pipeline\n简版中英双语实验报告")
    set_run_font(title_run, size=24, color=INK, bold=True)

    subtitle = doc.add_paragraph(style="Subtitle")
    subtitle_run = subtitle.add_run("Concise Bilingual Experiment Report")
    set_run_font(subtitle_run, size=13, color=MUTED)

    add_table(
        doc,
        ["项目 / Item", "内容 / Value"],
        [
            ["报告日期 / Date", "2026-08-04"],
            ["主要模型 / Main model", "Local Ollama llama3.1:8b"],
            ["研究对象 / Research object", "Video-derived industrial text -> Procedural Knowledge Graph"],
            ["主要变量 / Main variables", "Raw vs Unified; One-shot vs Layered"],
            ["Gold 原则 / Gold policy", "Only source-supported facts"],
        ],
        [2550, 6810],
        font_size=8.7,
        first_column_bold=True,
    )
    rule = doc.add_paragraph()
    set_paragraph_border_bottom(rule, color=BLUE, size=12)
    add_callout(
        doc,
        "核心结论 / Key takeaway",
        "工业端到端实验的最佳 Node F1 为 0.6019，最佳 Edge F1 为 0.1421。关系仍是主要瓶颈。The best industrial end-to-end Node F1 is 0.6019, while the best Edge F1 is 0.1421. Relation extraction remains the primary bottleneck.",
    )

    doc.add_page_break()
    doc.add_heading("1. 研究目的与实验设计 / Objective and Design", level=1)
    add_bilingual(
        doc,
        "本项目研究如何通过统一文本结构预处理和逐层抽取，提高小型语言模型从视频衍生工业操作文本生成程序性知识图谱的质量与稳定性。研究范围从 video-to-text 之后开始，不直接处理原始视频帧。",
        "This project studies whether unified text-structure preprocessing and layered extraction improve the quality and stability of procedural knowledge graphs generated by small LLMs from video-derived industrial text. The scope starts after video-to-text conversion and excludes raw-frame processing.",
    )
    add_bilingual_bullets(
        doc,
        [
            ("Raw：原始场景描述", "Raw: original scene description"),
            ("Unified：仅重组原文支持事实的统一字段", "Unified: fixed fields containing only source-supported facts"),
            ("One-shot：一次生成完整结构", "One-shot: generate the complete structure in one call"),
            ("Layered：先抽实体，再抽关系", "Layered: extract entities first and relations second"),
        ],
    )

    doc.add_heading("1.1 评价标准 / Evaluation Metrics", level=2)
    add_table(
        doc,
        ["指标 / Metric", "中文解释", "English interpretation"],
        [
            ["Precision", "预测事实中有多少正确", "Correct facts among all predicted facts"],
            ["Recall", "Gold 事实中有多少被找到", "Recovered facts among all Gold facts"],
            ["F1", "Precision 与 Recall 的调和平均", "Harmonic mean of Precision and Recall"],
            ["Hallucination", "无原文或 schema 支持的节点/关系", "Nodes or edges unsupported by source/schema"],
            ["Stability", "重复运行图集合的一致程度", "Agreement between graphs from repeated runs"],
        ],
        [1650, 3600, 4110],
        font_size=8.1,
        first_column_bold=True,
    )
    add_callout(
        doc,
        "解释边界 / Interpretation boundary",
        "Graph overlap=1.0 只说明输出重复一致，不说明输出正确。Graph overlap=1.0 means repeated outputs agree; it does not prove correctness.",
        risk=True,
    )

    doc.add_heading("1.2 早期可行性试验 / Early Feasibility Pilot", level=2)
    add_table(
        doc,
        ["Input", "Runs", "Schema success", "Node F1", "Relation F1"],
        [
            ["Raw", 5, "3/5", "0.4638", "0.1818"],
            ["Unified", 5, "5/5", "0.5000", "0.0000"],
        ],
        [1800, 1200, 2200, 2080, 2080],
        font_size=8.5,
        first_column_bold=True,
    )
    add_bilingual(
        doc,
        "统一结构提高了本轮 schema 成功率，但没有提高关系质量。这一结果推动项目把实体和关系拆开，并单独优化关系阶段。",
        "Unified input improved schema success in this pilot but did not improve relation quality. This motivated separating entity and relation extraction and optimizing the relation stage independently.",
    )
    add_source_note(doc, "docs/results/local_experiment_2026-05-26_r1.md")

    doc.add_heading("2. EASG 真实 LLM 实验 / EASG Real-LLM Experiment", level=1)
    add_bilingual(
        doc,
        "EASG 实验使用 10 条 annotation-derived scenes，每个条件重复 2 次，共 80 次真实本地 LLM 运行。轻量 JSON 修复层只修复输出语法，不补充缺失事实。",
        "The EASG experiment used 10 annotation-derived scenes, two repetitions per condition, and 80 real local-LLM runs. The lightweight JSON repair layer corrected output syntax only and did not invent missing facts.",
    )
    add_figure(
        doc,
        easg_chart,
        "图 1 / Figure 1. EASG 10 场景真实 LLM 的 Node 与 Edge F1",
        "EASG ten-scene real LLM Node and Edge F1 chart",
    )
    add_bilingual(
        doc,
        "Raw+Layered 的 Node F1 最高，为 0.8898；四种条件的 Edge F1 约为 0.38-0.41。所有 80 次运行均无解析或运行错误，但统一结构并不保证 F1 更高。",
        "Raw+Layered achieved the highest Node F1 at 0.8898. Edge F1 remained around 0.38-0.41 across conditions. All 80 runs completed without parsing/runtime errors, but unified input did not guarantee a higher F1.",
    )
    add_callout(
        doc,
        "限制 / Limitation",
        "EASG 是第一人称动作场景图数据，不是最终工业制造 benchmark。EASG is an egocentric action-scene-graph dataset, not the final industrial manufacturing benchmark.",
        risk=True,
    )
    add_source_note(doc, "docs/results/easg_real_llm_lightweight_realtest_10scene_2026-06-20.md")

    doc.add_heading("3. 工业端到端实验 / Industrial End-to-End Experiment", level=1)
    add_bilingual(
        doc,
        "该实验使用 5 条工业场景、4 个条件和每条件 2 次重复，共 40 次 llama3.1:8b 调用。所有条件均为 0 error。",
        "This experiment used five industrial scenes, four conditions, and two repetitions per condition, totaling 40 llama3.1:8b calls. All conditions completed with zero errors.",
    )
    add_figure(
        doc,
        industrial_chart,
        "图 2 / Figure 2. 五场景工业端到端 Node 与 Edge F1",
        "Industrial five-scene end-to-end Node and Edge F1 chart",
    )
    add_bilingual_bullets(
        doc,
        [
            ("最佳 Node F1：Unified+Layered，0.6019", "Best Node F1: Unified+Layered, 0.6019"),
            ("最佳 Edge F1：Raw+One-shot，0.1421", "Best Edge F1: Raw+One-shot, 0.1421"),
            ("Layered 改善了节点结果，但没有稳定改善关系", "Layered extraction improved nodes but did not consistently improve relations"),
            ("32/40 次运行包含至少一条 llm_extracted 边", "32 of 40 runs contained at least one llm_extracted edge"),
        ],
    )
    add_callout(
        doc,
        "当前解释 / Current interpretation",
        "Unified+Layered 是当前较好的节点抽取路径，但不能声称它已经解决关系抽取。Unified+Layered is currently strong for node extraction, but it has not solved relation extraction.",
    )
    add_source_note(doc, "docs/results/industrial_full_after_relation_fix_2026-07-05.md")

    doc.add_heading("4. 关系候选消融 / Relation Candidate Ablation", level=1)
    add_bilingual(
        doc,
        "该实验保持同一实体抽取结果，只替换关系阶段，用于判断有限候选和二元判断是否比当前最小关系方法更有效。",
        "This ablation kept entity extraction constant and changed only the relation stage to test whether constrained candidates and binary validation outperform the current minimal relation method.",
    )
    add_figure(
        doc,
        ablation_chart,
        "图 3 / Figure 3. 三种关系方法的 Edge F1（纵轴范围 0-0.10）",
        "Edge F1 comparison for three relation candidate methods with y axis from zero to point one",
    )
    add_table(
        doc,
        ["Method", "Edge F1", "Runtime(s)", "Interpretation"],
        [
            ["Minimal candidate", "0.0476", "19.34", "Baseline"],
            ["Deterministic rules", "0.0476", "0.00", "More edges, no F1 gain"],
            ["LLM binary judge", "0.0564", "81.84", "Small precision gain, high cost"],
        ],
        [2800, 1500, 1700, 3360],
        font_size=8.2,
        first_column_bold=True,
    )
    add_bilingual(
        doc,
        "LLM binary judge 将 Edge F1 提高了 0.0088，但平均耗时明显增加。它更像 precision filter，而不是修复 recall 的方法。",
        "The LLM binary judge improved Edge F1 by 0.0088 but substantially increased runtime. It acts mainly as a precision filter rather than a recall-repair mechanism.",
    )
    add_source_note(doc, "docs/results/relation_candidate_ablation_2026-07-07.md")

    doc.add_heading("5. 人工 Gold 关系诊断 / Reviewed-Gold Relation Diagnostic", level=1)
    add_bilingual(
        doc,
        "该诊断直接向关系候选模块提供人工审核的 Gold entities，用于隔离关系阶段的候选覆盖能力。数据包括 32 个 scenes、674 个实体和 828 条关系。",
        "This diagnostic supplied human-reviewed Gold entities directly to the relation candidate module to isolate relation-stage coverage. The dataset contains 32 scenes, 674 entities, and 828 relations.",
    )
    add_figure(
        doc,
        relation_chart,
        "图 4 / Figure 4. 32 场景 Gold-entity 关系类型诊断",
        "Reviewed Gold entity relation diagnostic by relation type",
    )
    add_table(
        doc,
        ["Relation", "Gold", "Precision", "Recall", "F1"],
        [
            ["ACTS_ON", 405, "0.8695", "0.8222", "0.8452"],
            ["BEFORE", 329, "0.9763", "1.0000", "0.9880"],
            ["USES_TOOL", 94, "0.5283", "0.2979", "0.3810"],
            ["Overall", 828, "0.8926", "0.8333", "0.8620"],
        ],
        [2100, 1400, 1950, 1950, 1960],
        font_size=8.4,
        first_column_bold=True,
    )
    add_callout(
        doc,
        "重要说明 / Important note",
        "0.8620 是 Gold-entity 关系阶段诊断，不是端到端 LLM F1。0.8620 is a Gold-entity relation-stage diagnostic score, not an end-to-end LLM F1 score.",
        risk=True,
    )
    add_bilingual(
        doc,
        "BEFORE 已接近完整覆盖，ACTS_ON 基本可用；USES_TOOL Recall 只有 0.2979，是当前候选生成器最明显的缺口。",
        "BEFORE is nearly fully covered and ACTS_ON is broadly usable. USES_TOOL recall is only 0.2979 and remains the clearest candidate-generator weakness.",
    )
    add_source_note(doc, "docs/results/industrial_reviewed_gold_combined_relation_diagnostic_2026-08-01.md")

    doc.add_heading("6. 总结、限制与下一步 / Conclusions, Limitations and Next Steps", level=1)
    doc.add_heading("6.1 可靠结论 / Supported Conclusions", level=2)
    add_bilingual_bullets(
        doc,
        [
            ("统一文本最稳定的作用是改善 schema、ID 和格式可用性", "The most reliable benefit of unified text is better schema, ID, and format usability"),
            ("逐层抽取有助于节点识别和错误定位，但没有稳定提高 Edge F1", "Layered extraction supports node recognition and debugging but has not consistently improved Edge F1"),
            ("关系质量受实体遗漏、端点命名和候选覆盖共同限制", "Relation quality is limited by entity omissions, endpoint naming, and candidate coverage"),
            ("稳定性必须与正确性同时报告", "Stability must be reported together with correctness"),
            ("后处理可以修复别名、方向和重复边，但不能恢复没有抽取出的事实", "Post-processing can fix aliases, direction, and duplicates but cannot recover omitted facts"),
        ],
    )

    doc.add_heading("6.2 当前限制 / Current Limitations", level=2)
    add_bilingual_bullets(
        doc,
        [
            ("工业端到端正式实验仍只有 5 个 scenes", "The formal industrial end-to-end experiment still contains only five scenes"),
            ("32-scene 结果属于关系阶段诊断，不是完整模型 benchmark", "The 32-scene result is a relation-stage diagnostic, not a complete model benchmark"),
            ("完整 dependency graph、tree decomposition 和跨局部子图合并尚未完成", "The full dependency graph, tree decomposition, and cross-subgraph merge remain incomplete"),
            ("当前主要使用单一本地模型，不能形成可靠模型排名", "The project mainly uses one local model and cannot yet provide a reliable model ranking"),
        ],
    )

    doc.add_heading("6.3 下一步 / Next Steps", level=2)
    add_bilingual_bullets(
        doc,
        [
            ("提高 USES_TOOL 候选召回，支持共享工具和跨句证据", "Improve USES_TOOL candidate recall for shared tools and cross-sentence evidence"),
            ("在 32 个工业 scenes 上运行至少两次端到端四条件实验", "Run at least two repetitions of all four end-to-end conditions on 32 industrial scenes"),
            ("按 video_id 划分数据，防止同一视频片段泄漏", "Split data by video_id to prevent leakage between clips from the same video"),
            ("联合报告 raw、normalized、hallucination 和 stability 指标", "Report raw, normalized, hallucination, and stability metrics together"),
            ("后续再接入程序依赖图和真正的局部子任务分解", "Add procedural dependency graphs and true local-subtask decomposition in a later phase"),
        ],
    )

    doc.add_heading("6.4 结果文件 / Result Files", level=2)
    add_table(
        doc,
        ["实验 / Experiment", "来源文件 / Source file"],
        [
            ["Early pilot", "docs/results/local_experiment_2026-05-26_r1.md"],
            ["EASG 10-scene", "docs/results/easg_real_llm_lightweight_realtest_10scene_2026-06-20.md"],
            ["Industrial end-to-end", "docs/results/industrial_full_after_relation_fix_2026-07-05.md"],
            ["Candidate ablation", "docs/results/relation_candidate_ablation_2026-07-07.md"],
            ["Reviewed Gold diagnostic", "docs/results/industrial_reviewed_gold_combined_relation_diagnostic_2026-08-01.md"],
        ],
        [2900, 6460],
        font_size=7.9,
        first_column_bold=True,
    )

    doc.core_properties.title = "AUT KG Extraction Pipeline - Simple Bilingual Experiment Report"
    doc.core_properties.subject = "Chinese-English summary of verified KG extraction experiments"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    return OUTPUT


if __name__ == "__main__":
    print(build_document())
